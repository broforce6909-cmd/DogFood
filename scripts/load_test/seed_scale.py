"""Seed a large synthetic event directly into the database, for load testing.

This is the Phase 5 load pass's own tool, generalised and committed: that pass
seeded 200 submissions / 50 judges / ~1,000 ballots / 1,500 votes "directly
into a running instance" (see ARCHITECTURE.md's "Measured, not assumed, at
5-10x the seeded fixtures") but never checked the script in. This one is
checked in, and goes further -- 1,000+ submissions, 500+ judges, 50,000+
votes, 100,000+ audit events -- to answer the same question at the next
order of magnitude up.

Run against the compose stack's Postgres, from the host, using the backend's
own virtualenv so it sees the same SQLAlchemy models the app does:

    DATABASE_URL=postgresql+psycopg://dogfood:dogfood@localhost:55432/dogfood \\
        backend/.venv/Scripts/python.exe scripts/load_test/seed_scale.py

(Port 55432 assumes the stack was brought up with `DOGFOOD_DB_PORT=55432`,
the workaround for a host Postgres already on 5432 -- see docker-compose.yml
and README.md.)

Writes go straight to the tables through the same ORM models `app/` uses, not
through the API -- 150,000+ rows is not something anyone should wait on FastAPI
request/response overhead plus per-request auth for, and this script is testing
what happens *after* that data exists, not the write paths that normally
create it (those already have their own tests). The one exception is the audit
log: `app.audit.record()`'s hash chain is reused byte-for-byte
(`_hash_fields`/`_chain_hash`, imported, not reimplemented) so the 100,000+
rows this seeds are real, verifiable links -- `GET /api/audit/verify` cannot
tell them apart from ones a real request wrote one at a time. Chaining still
needs `record()`'s advisory lock (a concurrent real write during the seed
would otherwise compute the same "previous hash" this script just read), and
the identity sequence backing `seq` needs to be pushed forward afterward,
since inserting explicit values with `OVERRIDING SYSTEM VALUE` does not do
that on its own -- skip it and the very next real audit write collides on
`uq_audit_log_seq`.

Idempotent at the event level, not additive: re-running this deletes any
prior `load-test` event (cascades to its teams/submissions/judges/
assignments/scores/voters/votes) and rebuilds it fresh, so the numbers this
prints always describe exactly one seed pass, never several stacked on top of
each other. Audit rows are the one thing that outlives the event (`event_id`
is `ON DELETE SET NULL`, on purpose -- see `AuditEntry`'s own docstring), so
re-running does add another 100,000+ of those; this script is meant to be run
once per measurement session, not on every container start like `app.seed`.
"""

