def test_a_judge_with_no_spread_across_many_ballots_is_flagged() -> None:
    """4+ ballots, every one the same value -- the same pattern `flat` catches
    for scoring purposes, but here gated on `min_reviews` so it reads as a
    real pattern (many independent ballots, zero spread) rather than firing
    on a single low-information data point the way `flat` correctly does."""
    ballots, criteria, judges, _ = _one_criterion(
        {
            "uniform": {"p1": 3, "p2": 3, "p3": 3, "p4": 3},
            "normal": {"p1": 1, "p2": 3, "p3": 5, "p4": 2},
        }
    )
    flags = near_identical_score_flags(normalize(ballots, criteria))
    flagged_judges = {f.judge_id for f in flags}
    assert judges["uniform"] in flagged_judges
    assert judges["normal"] not in flagged_judges
    assert all(f.reason == "near_identical_scores" for f in flags)


def test_a_judge_with_too_few_ballots_is_not_flagged_even_if_uniform() -> None:
    """Two identical-looking ballots is not a pattern -- `min_reviews` gates
    this signal so a judge is not flagged on essentially no evidence."""
    ballots, criteria, judges, _ = _one_criterion({"new": {"p1": 3, "p2": 3}})
    flags = near_identical_score_flags(normalize(ballots, criteria))
    assert judges["new"] not in {f.judge_id for f in flags}


def test_near_identical_thresholds_are_configurable() -> None:
    ballots, criteria, judges, _ = _one_criterion({"a": {"p1": 3, "p2": 3, "p3": 3, "p4": 3}})
    results = normalize(ballots, criteria)
    assert near_identical_score_flags(results, min_reviews=10) == []
    assert near_identical_score_flags(results, sd_threshold=-1.0) == []


# One reference instant for the whole module. Only the gaps between a judge's
# completions matter to the signal, so it does not have to be any particular date.
_BASE = datetime.now(timezone.utc)


def _timing(judge: uuid.UUID, submission: uuid.UUID, seconds_offset: float) -> AssignmentTiming:
    return AssignmentTiming(
        judge_id=judge, submission_id=submission, completed_at=_BASE + timedelta(seconds=seconds_offset)
    )


def test_two_ballots_finished_seconds_apart_are_flagged() -> None:
    judge, a, b = uuid.uuid4(), uuid.uuid4(), uuid.uuid4()
    timings = [_timing(judge, a, 0), _timing(judge, b, 5)]
    flags = fast_completion_flags(timings)
    assert len(flags) == 1
    assert flags[0].judge_id == judge
    assert flags[0].reason == "fast_completion"


def test_ballots_finished_far_apart_are_not_flagged() -> None:
    judge, a, b = uuid.uuid4(), uuid.uuid4(), uuid.uuid4()
    timings = [_timing(judge, a, 0), _timing(judge, b, 3600)]
    assert fast_completion_flags(timings) == []


def test_a_single_completed_ballot_has_nothing_to_compare_against() -> None:
    judge, a = uuid.uuid4(), uuid.uuid4()
    assert fast_completion_flags([_timing(judge, a, 0)]) == []


def test_fast_completion_is_scoped_per_judge() -> None:
    """Two different judges each finishing a ballot around the same moment is
    not a pattern -- the gap only means something between the *same* judge's
    consecutive completions."""
    judge_a, judge_b, sub_a, sub_b = uuid.uuid4(), uuid.uuid4(), uuid.uuid4(), uuid.uuid4()
    timings = [_timing(judge_a, sub_a, 0), _timing(judge_b, sub_b, 2)]
    assert fast_completion_flags(timings) == []


def test_fast_completion_threshold_is_configurable() -> None:
    judge, a, b = uuid.uuid4(), uuid.uuid4(), uuid.uuid4()
    timings = [_timing(judge, a, 0), _timing(judge, b, 5)]
    assert fast_completion_flags(timings, threshold_seconds=1.0) == []
    assert len(fast_completion_flags(timings, threshold_seconds=10.0)) == 1
