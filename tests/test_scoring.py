def test_equal_scores_share_a_rank_and_the_next_one_skips() -> None:
    """Competition ranking: 1, 1, 3 -- not 1, 1, 2. Two projects genuinely tied
    for first means nothing is second."""
    ballots, criteria, _, submissions = _one_criterion(
        {"a": {"p1": 5, "p2": 5, "p3": 1}}
    )
    results = normalize(ballots, criteria)
    ranks = sorted(r.normalized_rank for r in results.submissions)
    assert ranks == [1, 1, 3]


def test_rank_delta_is_positive_when_normalization_promotes() -> None:
    """Sign convention, asserted so the dashboard cannot display it backwards."""
    ballots, criteria, _, _ = _one_criterion(
        {
            "harsh": {"p1": 1, "p2": 2, "p3": 3},
            "generous": {"p1": 5, "p2": 5, "p3": 4},
        }
    )
    results = normalize(ballots, criteria)
    for row in results.submissions:
        assert row.rank_delta == row.raw_rank - row.normalized_rank


def test_results_come_back_sorted_by_normalized_rank() -> None:
    ballots, criteria, _, _ = _one_criterion(
        {"a": {"p1": 1, "p2": 5, "p3": 3}}
    )
    results = normalize(ballots, criteria)
    assert [r.normalized_rank for r in results.submissions] == sorted(
        r.normalized_rank for r in results.submissions
    )


def test_no_ballots_is_an_empty_result_not_an_error() -> None:
    results = normalize([], [criterion("a", 1)])
    assert results.submissions == []
    assert results.global_mean == 0.0


def test_a_ballot_with_no_scores_is_ignored_entirely() -> None:
    """An assigned-but-unscored ballot must not drag a project toward zero."""
    only = criterion("only", 1)
    sub = uuid.uuid4()
    ballots = [
        Ballot(uuid.uuid4(), sub, {only.id: 4}),
        Ballot(uuid.uuid4(), sub, {}),  # assigned, never filled in
    ]
    results = normalize(ballots, [only])
    row = results.by_id(sub)
    assert row is not None
    assert row.n_reviews == 1
    assert row.raw_mean == pytest.approx(4.0)


