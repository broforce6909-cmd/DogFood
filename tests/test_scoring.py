def criterion(key: str, weight: float, *, lo: int = 1, hi: int = 5) -> Criterion:
    return Criterion(
        id=uuid.uuid4(), key=key, name=key.title(), weight=weight, min_score=lo, max_score=hi
    )


# --------------------------------------------------------------------------- #
# 1. The weighted rubric
# --------------------------------------------------------------------------- #


def test_a_weighted_mean_is_a_weighted_mean() -> None:
    """impact×3 scored 5, craft×1 scored 1  ->  (15 + 1) / 4 = 4.0"""
    impact = criterion("impact", 3)
    craft = criterion("craft", 1)
    b = Ballot(uuid.uuid4(), uuid.uuid4(), {impact.id: 5, craft.id: 1})
    assert raw_score(b, [impact, craft]) == pytest.approx(4.0)


def test_the_weighted_mean_works_on_continuous_scores_too() -> None:
    """`raw_score` never assumed whole numbers -- `float(value)` was already
    the first thing it did to every score. This just says so out loud for the
    move off a discrete `scores.value` column."""
    impact = criterion("impact", 3)
    craft = criterion("craft", 1)
    b = Ballot(uuid.uuid4(), uuid.uuid4(), {impact.id: 4.5, craft.id: 3.1})
    assert raw_score(b, [impact, craft]) == pytest.approx((4.5 * 3 + 3.1) / 4)


def test_weights_are_relative_not_absolute() -> None:
    """Doubling every weight must not move a single score.

    This is the property that lets an organizer type 10 and 20 instead of 1 and 2
    without rescaling the event, and the reason weights are divided by their own
    sum at read time.
    """
    small = [criterion("a", 3), criterion("b", 1)]
    large = [
        Criterion(id=small[0].id, key="a", name="A", weight=30),
        Criterion(id=small[1].id, key="b", name="B", weight=10),
    ]
    b = Ballot(uuid.uuid4(), uuid.uuid4(), {small[0].id: 5, small[1].id: 2})
    assert raw_score(b, small) == pytest.approx(raw_score(b, large))


def test_an_equal_weighted_rubric_is_a_plain_mean() -> None:
    a, b_, c = criterion("a", 1), criterion("b", 1), criterion("c", 1)
    b = Ballot(uuid.uuid4(), uuid.uuid4(), {a.id: 1, b_.id: 4, c.id: 4})
    assert raw_score(b, [a, b_, c]) == pytest.approx(3.0)


def test_a_partial_ballot_weights_over_what_is_present() -> None:
    """A ballot missing a criterion is not scored as if that criterion were zero.

    Scoring it as zero would punish the project for the judge's incomplete work.
    The routes refuse to mark such a ballot complete, which is where that rule
    belongs; this function just declines to invent data.
    """
    impact = criterion("impact", 3)
    craft = criterion("craft", 1)
    b = Ballot(uuid.uuid4(), uuid.uuid4(), {impact.id: 4})
    assert raw_score(b, [impact, craft]) == pytest.approx(4.0)


def test_an_empty_ballot_is_none_not_zero() -> None:
    """None and 0.0 mean very different things to the mean that consumes this."""
    assert raw_score(Ballot(uuid.uuid4(), uuid.uuid4(), {}), [criterion("a", 1)]) is None


