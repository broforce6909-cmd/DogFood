def _one_criterion(scores_by_judge: dict[str, dict[str, int]]):
    """Build ballots for a single unit-weight criterion.

    With one criterion of weight 1, `raw == the score the judge gave`, which
    keeps these tests about normalization rather than about weighting.
    """
    only = criterion("only", 1)
    judges = {name: uuid.uuid4() for name in scores_by_judge}
    submissions: dict[str, uuid.UUID] = {}
    for per_judge in scores_by_judge.values():
        for sub in per_judge:
            submissions.setdefault(sub, uuid.uuid4())
    ballots = [
        Ballot(judges[judge], submissions[sub], {only.id: value})
        for judge, per_judge in scores_by_judge.items()
        for sub, value in per_judge.items()
    ]
    return ballots, [only], judges, submissions


def test_a_judge_who_marks_everything_the_same_is_flagged_flat() -> None:
    ballots, criteria, judges, _ = _one_criterion(
        {
            "flat": {"p1": 3, "p2": 3, "p3": 3},
            "spread": {"p1": 1, "p2": 3, "p3": 5},
        }
    )
    results = normalize(ballots, criteria)
    by_judge = {c.judge_id: c for c in results.calibrations}
    assert by_judge[judges["flat"]].flat is True
    assert by_judge[judges["spread"]].flat is False
    assert "no ordering" in by_judge[judges["flat"]].note


def test_a_flat_judge_contributes_exactly_the_global_mean() -> None:
    """Their ballots say "all of these are average", because that is the only
    thing a constant ballot can mean. Not a division by a fudge factor: an
    explicit z of zero, which maps back to the global mean on rescaling.
    """
    ballots, criteria, judges, submissions = _one_criterion(
        {
            "flat": {"p1": 3, "p2": 3, "p3": 3},
            "spread": {"p1": 1, "p2": 3, "p3": 5},
        }
    )
    results = normalize(ballots, criteria)
    flat = judges["flat"]
    for row in results.submissions:
        assert row.per_judge[flat] == pytest.approx(results.global_mean)


def test_a_flat_judge_does_not_decide_the_ranking() -> None:
    """The flat judge rates everything 5 -- the most generous possible ballot --
    and the ordering still comes entirely from the judge who discriminated."""
    ballots, criteria, judges, submissions = _one_criterion(
        {
            "generous_flat": {"p1": 5, "p2": 5, "p3": 5},
            "spread": {"p1": 1, "p2": 3, "p3": 5},
        }
    )
    results = normalize(ballots, criteria)
    ordered = [r.submission_id for r in sorted(results.submissions, key=lambda r: r.normalized_rank)]
    assert ordered == [submissions["p3"], submissions["p2"], submissions["p1"]]


def test_every_judge_flat_is_a_dead_heat_not_a_crash() -> None:
    """The degenerate case. Global sd is zero, every z is zero, everything ties --
    which is the correct answer, and the one most likely to divide by zero."""
    ballots, criteria, _, _ = _one_criterion(
        {"a": {"p1": 3, "p2": 3}, "b": {"p1": 3, "p2": 3}}
    )
    results = normalize(ballots, criteria)
    assert results.global_sd == pytest.approx(0.0)
    assert {r.normalized_rank for r in results.submissions} == {1}


# --------------------------------------------------------------------------- #
# 4. Harshness cancels
# --------------------------------------------------------------------------- #


def test_harshness_cancels_when_orderings_agree(monkeypatch) -> None:
    """THE property the whole method exists for.

    Two judges who rank three projects identically but live two points apart on
    the scale must produce the same normalized score for each project. Shrinkage
    is switched off for this one assertion, because shrinkage deliberately does
    *not* fully remove a judge effect when n is small -- that is its job -- and
    mixing the two would test neither cleanly.
    """
    monkeypatch.setattr("app.scoring.SHRINKAGE_K", 0.0)
    ballots, criteria, judges, _ = _one_criterion(
        {
            "harsh": {"p1": 1, "p2": 2, "p3": 3},
            "generous": {"p1": 3, "p2": 4, "p3": 5},
        }
    )
    results = normalize(ballots, criteria)
    for row in results.submissions:
        harsh = row.per_judge[judges["harsh"]]
        generous = row.per_judge[judges["generous"]]
        assert harsh == pytest.approx(generous), "a judge's level survived normalization"


def test_raw_scores_do_not_cancel_harshness() -> None:
    """The control for the test above: without normalization, the project the
    harsh judge happened to draw is simply worse off. This is the bug the whole
    module exists to fix, asserted so it cannot silently come back."""
    ballots, criteria, _, submissions = _one_criterion(
        {
            "harsh": {"p1": 1, "p2": 2},
            "generous": {"p3": 4, "p4": 5},
        }
    )
    results = normalize(ballots, criteria)
    raw = {r.submission_id: r.raw_mean for r in results.submissions}
    assert raw[submissions["p2"]] < raw[submissions["p3"]]


def test_a_judges_own_ordering_is_always_preserved(monkeypatch) -> None:
    """Normalization may move a project relative to others; it must never
    reorder one judge's own opinions, because a monotonic transform cannot."""
    monkeypatch.setattr("app.scoring.SHRINKAGE_K", 0.0)
    ballots, criteria, judges, submissions = _one_criterion(
        {"j": {"p1": 1, "p2": 3, "p3": 4, "p4": 5}}
    )
    results = normalize(ballots, criteria)
    # A single judge with spread: their normalized values must rise with their raw.
    j = judges["j"]
    pairs = sorted(
        ((r.raw_mean, r.per_judge[j]) for r in results.submissions), key=lambda p: p[0]
    )
    normalized_in_raw_order = [p[1] for p in pairs]
    assert normalized_in_raw_order == sorted(normalized_in_raw_order)


# --------------------------------------------------------------------------- #
# 5. Small n
# --------------------------------------------------------------------------- #


def test_a_judge_with_few_ballots_is_pulled_toward_the_field() -> None:
    """A judge with three ballots has a badly estimated mean, so we trust it less.

    Asserted as a direction rather than a value: the shrunk mean must sit between
    the judge's own and the global one, and nearer the global one than an
    unshrunk estimate would be.
    """
    ballots, criteria, judges, _ = _one_criterion(
        {
            "brief": {"p1": 5, "p2": 5, "p3": 4},
            "thorough": {f"q{i}": (i % 5) + 1 for i in range(30)},
        }
    )
    results = normalize(ballots, criteria)
    brief = next(c for c in results.calibrations if c.judge_id == judges["brief"])
    thorough = next(c for c in results.calibrations if c.judge_id == judges["thorough"])

    assert min(brief.mean, results.global_mean) <= brief.shrunk_mean <= max(
        brief.mean, results.global_mean
    )
    # The judge with 30 ballots is trusted nearly completely; the one with 3 is not.
    assert abs(thorough.shrunk_mean - thorough.mean) < abs(brief.shrunk_mean - brief.mean)
    assert "heavily shrunk" in brief.note


