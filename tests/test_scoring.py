def test_a_single_track_group_matches_plain_normalize() -> None:
    """`normalize_by_track` must be a strict generalisation: one track (or
    none) is the common case and has to behave exactly like `normalize`."""
    ballots, criteria, _, submissions = _one_criterion(
        {"a": {"p1": 1, "p2": 3, "p3": 5}, "b": {"p1": 2, "p2": 3, "p3": 4}}
    )
    plain = normalize(ballots, criteria)
    track_of = {sub: None for sub in submissions.values()}
    tracked = normalize_by_track(ballots, criteria, track_of)

    plain_by_id = {r.submission_id: r.normalized_mean for r in plain.submissions}
    tracked_by_id = {r.submission_id: r.normalized_mean for r in tracked.submissions}
    assert plain_by_id == pytest.approx(tracked_by_id)


def test_a_cross_track_judge_gets_one_calibration_per_track() -> None:
    """The bug this function exists to fix: a judge who reviews two tracks
    harshly on one and generously on the other must not be averaged into a
    single, wrong calibration for both."""
    only = criterion("only", 1)
    judge = uuid.uuid4()
    a1, a2, b1, b2 = (uuid.uuid4() for _ in range(4))
    track_a, track_b = uuid.uuid4(), uuid.uuid4()
    ballots = [
        Ballot(judge, a1, {only.id: 1}),
        Ballot(judge, a2, {only.id: 1}),
        Ballot(judge, b1, {only.id: 5}),
        Ballot(judge, b2, {only.id: 5}),
    ]
    track_of = {a1: track_a, a2: track_a, b1: track_b, b2: track_b}

    result = normalize_by_track(ballots, [only], track_of)
    cals = [c for c in result.calibrations if c.judge_id == judge]
    assert len(cals) == 2
    means = sorted(c.mean for c in cals)
    assert means == [pytest.approx(1.0), pytest.approx(5.0)]
    tracks = {c.track_id for c in cals}
    assert tracks == {track_a, track_b}


def test_track_restricted_judges_are_untouched_by_normalize_by_track() -> None:
    """A judge who only ever sees one track produces exactly the calibration
    they would from plain `normalize` scoped to that track alone."""
    ballots, criteria, judges, submissions = _one_criterion(
        {"harsh": {"p1": 1, "p2": 2}, "generous": {"p1": 5, "p2": 4}}
    )
    track = uuid.uuid4()
    track_of = {sub: track for sub in submissions.values()}
    result = normalize_by_track(ballots, criteria, track_of)
    assert len(result.calibrations) == 2
    assert all(c.track_id == track for c in result.calibrations)


