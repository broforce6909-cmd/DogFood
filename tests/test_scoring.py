def test_sd_of_one_observation_is_zero_not_undefined() -> None:
    """A judge with a single ballot has no spread. Returning 0 rather than raising
    hands them to the flat-judge rule, which is where they should be handled."""
    assert _sd([4.0]) == 0.0
    assert _sd([]) == 0.0


def test_population_sd_on_a_hand_checkable_case() -> None:
    """[1, 3]: mean 2, deviations ±1, population variance 1, sd 1."""
    assert _sd([1.0, 3.0]) == pytest.approx(1.0)


def test_shrinkage_with_n_equal_to_k_is_the_midpoint() -> None:
    assert _shrink(own=10.0, global_value=0.0, n=int(SHRINKAGE_K)) == pytest.approx(5.0)


