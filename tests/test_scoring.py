def test_judges_who_agree_are_not_flagged() -> None:
    ballots, criteria, _, submissions = _one_criterion(
        {"a": {"p1": 4, "p2": 3}, "b": {"p1": 4, "p2": 3}}
    )
    rows = disagreement(normalize(ballots, criteria))
    assert all(not r.needs_review for r in rows)
    assert all(r.mean_abs_pairwise_diff == pytest.approx(0.0) for r in rows)


def test_judges_who_disagree_wildly_are_flagged() -> None:
    """Each judge needs more than one ballot here on purpose: with exactly one,
    a judge's own `sd` is 0 by definition (see `_sd`) and they are classified
    `flat` -- correctly, since one data point has no measurable spread -- which
    would map both judges to the global mean and hide the disagreement this
    test exists to catch. A real disagreement signal needs judges who have
    demonstrated they *can* discriminate, and then didn't agree on `p1`.
    """
    ballots, criteria, _, submissions = _one_criterion(
        {
            "harsh": {"p1": 1, "p2": 3, "p3": 5},
            "generous": {"p1": 5, "p2": 3, "p3": 1},
        }
    )
    rows = disagreement(normalize(ballots, criteria))
    by_id = {r.submission_id: r for r in rows}
    p1 = by_id[submissions["p1"]]
    assert p1.needs_review is True
    assert p1.mean_abs_pairwise_diff > 0
    # p2 (3 and 3) is where the two judges agree, and must not be flagged.
    assert by_id[submissions["p2"]].needs_review is False


def test_a_lone_review_is_not_flagged_for_low_coverage() -> None:
    """One review cannot disagree with itself -- this is a coverage gap, not a
    disagreement, and `disagreement()` must not conflate the two."""
    ballots, criteria, _, _ = _one_criterion({"a": {"p1": 3}})
    rows = disagreement(normalize(ballots, criteria))
    assert len(rows) == 1
    assert rows[0].n_reviews == 1
    assert rows[0].needs_review is False
    assert rows[0].sd == 0.0


def test_disagreement_rows_are_sorted_worst_first() -> None:
    ballots, criteria, _, _ = _one_criterion(
        {
            "a": {"p1": 3, "p2": 3, "p3": 1},
            "b": {"p1": 3, "p2": 4, "p3": 5},
        }
    )
    rows = disagreement(normalize(ballots, criteria))
    diffs = [r.mean_abs_pairwise_diff for r in rows]
    assert diffs == sorted(diffs, reverse=True)


def test_a_judge_who_disagrees_with_consensus_is_flagged() -> None:
    """Calibration would call this judge merely harsh; after normalization
    already corrects for that, this judge *still* disagrees -- that residual
    is what `judge_deviation` measures and calibration cannot."""
    ballots, criteria, judges, _ = _one_criterion(
        {
            # Two judges agree closely across the board...
            "a": {"p1": 4, "p2": 3, "p3": 2},
            "b": {"p1": 4, "p2": 3, "p3": 2},
            # ...a third disagrees with the room on which project is best,
            # not just about how generous to be overall.
            "c": {"p1": 1, "p2": 4, "p3": 5},
        }
    )
    rows = judge_deviation(normalize(ballots, criteria))
    by_judge = {r.judge_id: r.mean_abs_deviation for r in rows}
    assert by_judge[judges["c"]] > by_judge[judges["a"]]
    assert by_judge[judges["c"]] > by_judge[judges["b"]]


