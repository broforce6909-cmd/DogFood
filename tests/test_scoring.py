"""The weighted rubric and the normalization maths.

No database, no HTTP, no fixtures -- `app.scoring` is pure functions over
dataclasses precisely so that the part of this project most likely to be argued
with can be tested with numbers a reader can check by hand.

Two kinds of assertion in here, and the split is deliberate:

* **Exact values**, where the arithmetic is simple enough to verify in your head:
  a weighted mean of two criteria, a shrinkage midpoint, a flat judge landing on
  the global mean.
* **Properties**, where it is not: that harshness cancels, that shrinkage pulls
  the right way, that ranking is invariant to things it should be invariant to.
  Asserting a hand-derived float to four places would mostly test my arithmetic.

The worked example on real fixture data lives in JUDGING.md and is generated by
`scripts/normalization_proof.py`, not by hand.
"""

